"""BBR code values as readable text, from the official code lists (https://teknik.bbr.dk/kodelister).

codes.json is generated by scripts/update_codes.py; FIELD_LISTS says which list each BBR field uses.
"""

import json
from functools import cache
from pathlib import Path
from typing import Any

FIELD_LISTS = {
    "status": "Livscyklus",
    # Bygning
    "byg021BygningensAnvendelse": "BygAnvendelse",
    "byg030Vandforsyning": "BygVandforsyning",
    "byg031Afloebsforhold": "BygAfloebsforhold",
    "byg032YdervaeggensMateriale": "YdervaeggenesMateriale",
    "byg033Tagdaekningsmateriale": "Tagdaekningsmateriale",
    "byg036AsbestholdigtMateriale": "AsbestholdigtMateriale",
    "byg056Varmeinstallation": "BygVarmeinstallation",
    "byg057Opvarmningsmiddel": "Opvarmningsmiddel",
    "byg058SupplerendeVarme": "BygSupplerendeVarme",
    "byg070Fredning": "Fredning",
    # Enhed
    "enh020EnhedensAnvendelse": "EnhAnvendelse",
    "enh023Boligtype": "Boligtype",
    "enh032Toiletforhold": "Toiletforhold",
    "enh033Badeforhold": "Badeforhold",
    "enh034Koekkenforhold": "Koekkenforhold",
    "enh035Energiforsyning": "Energiforsyning",
    "enh045Udlejningsforhold": "Udlejningsforhold",
    "enh051Varmeinstallation": "EnhVarmeinstallation",
    "enh052Opvarmningsmiddel": "Opvarmningsmiddel",
    "enh053SupplerendeVarme": "EnhSupplerendeVarme",
    # TekniskAnlaeg
    "tek020Klassifikation": "Klassifikation",
    "tek110Driftstatus": "Driftstatus",
}

CODES_FILE = Path(__file__).with_name("codes.json")


@cache
def code_lists() -> dict[str, dict[str, str]]:
    data = json.loads(CODES_FILE.read_text(encoding="utf-8"))
    return {name: values for name, values in data.items() if not name.startswith("_")}


def translate(field: str, value: Any) -> Any:
    """{"code", "text"} for a field with a code list; any other value unchanged."""
    list_name = FIELD_LISTS.get(field)
    if list_name is None or value is None:
        return value
    code = str(value)
    return {"code": code, "text": code_lists().get(list_name, {}).get(code, "unknown code")}
